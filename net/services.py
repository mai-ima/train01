def _line_of(a, b):
    for L, o in ORDER.items():
        if a in o and b in o:
            return L
    return None


def path_of(stops):
    out = [stops[0]]
    for a, b in zip(stops[:-1], stops[1:]):
        L = _line_of(a, b)
        if L is None:
            out.append(b)
            continue
        o = ORDER[L]
        i, j = o.index(a), o.index(b)
        seg = o[i:j + 1] if i <= j else o[j:i + 1][::-1]
        out += seg[1:]
    return out


def build():
    out = []
    for t in _S:
        p = path_of(t[4])
        passes = [x for x in p if x not in t[4]]
        out.append(t + (p, passes))
    return out


SVC = build()


def check():
    """整合検査: 旅客の貨物駅停車/臨時駅停車/往復の整合/重複停車駅。"""
    errs = []
    for t in SVC:
        if t[2] not in NONREV + ("貨物",) and any(s in FREIGHT_ONLY for s in t[4]):
            errs.append((t[0], "旅客列車が貨物専用駅に停車"))
        if t[2] not in ("臨時",) and any(s in SEASONAL for s in t[4]):
            errs.append((t[0], "定期列車が臨時乗降場に停車"))
        if len(set(t[4])) != len(t[4]):
            errs.append((t[0], "停車駅の重複"))
    return errs


