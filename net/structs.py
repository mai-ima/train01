def build():
    rnd = lambda s: random.Random(zlib.crc32(s.encode()))
    out = []
    for i, (kind, name, ln, a, b, fr, L, ex) in enumerate(R):
        ka, kb = S[a]["km"], S[b]["km"]
        km = None
        if ln in ("HM", "SH", "YB", "SR"):
            km = round(abs(ka) + (abs(kb - ka)) * fr if kb >= ka else abs(ka) - abs(kb - ka) * fr, 2)
        else:
            km = round(min(ka, kb) + abs(kb - ka) * fr, 2)
        out.append(dict(id=f"ST{i+1:02d}", kind=kind, kname=DEF[kind][0], color=DEF[kind][1], name=name, line=ln, a=a, b=b,
                        an=S[a]["name"], bn=S[b]["name"], km=km, len=L, **ex))
    return out


